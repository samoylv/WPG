# -*- coding: utf-8 -*-
"""
Surface height errors of mirrors and gratings as transmission elements (SRWLOptT).

The model is the one of SRW (``srwl_opt_setup_surf_height_1d/2d``): a height error h at the
point of the surface changes the optical path of the reflected wave by
``OPD = -(sin(theta) + sin(theta_r)) * h``, where theta and theta_r are the grazing angles of the
incident and reflected beams; the surface coordinate along the mirror is projected on the beam
cross-section with ``sin(theta_r)``. The height is interpolated linearly (bilinearly for a 2D map),
outside the measured profile it is 0. The functions here are vectorized: the same result as SRW
(tests/test_surface.py) without Python loops over the mesh.

Random surfaces with a power-law power spectral density (PSD) are generated by the spectral
method: white Gaussian noise filtered with sqrt(PSD) in Fourier space (Y. Z. Hu, K. Tonder,
Int. J. Mach. Tools Manuf. 32, 83 (1992), https://doi.org/10.1016/0890-6955(92)90064-N).

.. module:: wpg.surface
   :platform: Linux, Mac OSX, Windows
"""
from array import array

import numpy as np


def _mesh_axes(opt):
    """Coordinates of the SRWLOptT mesh relative to its centre: (x, y)."""
    m = opt.mesh
    x = np.linspace(m.xStart, m.xFin, m.nx) - getattr(opt, 'x', 0.)
    y = np.linspace(m.yStart, m.yFin, m.ny) - getattr(opt, 'y', 0.)
    return x, y


def _interp_inside(u, xp, fp):
    """Linear interpolation on [xp[0], xp[-1]) and 0 outside, as in SRW (x1 <= u < x2)."""
    h = np.interp(u, xp, fp)
    h[(u < xp[0]) | (u >= xp[-1])] = 0.
    return h


def _sorted_profile(x, h):
    x = np.asarray(x, dtype=float)
    h = np.asarray(h, dtype=float)
    if x.shape != h.shape or x.ndim != 1:
        raise ValueError('Profile: x and h should be 1D arrays of the same length')
    order = np.argsort(x, kind='stable')
    return x[order], h[order]


def fill_opd_1d(opt, x, h, orient, theta, theta_r=None, scale=1.):
    """
    Fill an SRWLOptT with the optical path difference of a 1D height profile (amplitude 1).

    :param opt: SRWLOptT, its mesh is the beam cross-section at the mirror
    :param x: positions along the mirror [m], relative to the mirror point on the beam axis
    :param h: height errors [m]
    :param orient: plane of deflection, 'x' or 'y'
    :param theta: grazing angle of the incident beam [rad]
    :param theta_r: grazing angle of the reflected beam [rad], None - theta (mirror)
    :param scale: factor for the heights
    :return: opt
    """
    theta_r = theta if theta_r is None else theta_r
    x, h = _sorted_profile(x, h)
    mx, my = _mesh_axes(opt)
    if orient == 'x':
        hu = _interp_inside(mx / np.sin(theta_r), x, h)[None, :] * np.ones((my.size, 1))
    elif orient == 'y':
        hu = _interp_inside(my / np.sin(theta_r), x, h)[:, None] * np.ones((1, mx.size))
    else:
        raise TypeError('orient should be "x" or "y"')
    _set_transmission(opt, -(np.sin(theta) + np.sin(theta_r)) * hu * scale)
    return opt


def fill_opd_2d(opt, x, y, h, orient, theta, theta_r=None, scale=1.):
    """
    Fill an SRWLOptT with the optical path difference of a 2D height map (amplitude 1).

    :param x: positions along the mirror [m], increasing, relative to the beam axis
    :param y: positions across the mirror [m], increasing
    :param h: height errors [m], shape (len(y), len(x))
    Other parameters as in :func:`fill_opd_1d`.
    """
    from scipy.interpolate import RegularGridInterpolator
    theta_r = theta if theta_r is None else theta_r
    x, y, h = np.asarray(x, float), np.asarray(y, float), np.asarray(h, float)
    if h.shape != (y.size, x.size):
        raise ValueError('Height map shape {} should be (len(y), len(x)) = {}'.format(h.shape, (y.size, x.size)))
    interp = RegularGridInterpolator((y, x), h, method='linear', bounds_error=False, fill_value=0.)
    mx, my = _mesh_axes(opt)
    if orient == 'x':
        long_, tr = np.meshgrid(mx / np.sin(theta_r), my)  # shape (ny, nx)
    elif orient == 'y':
        tr, long_ = np.meshgrid(mx, my / np.sin(theta_r))
    else:
        raise TypeError('orient should be "x" or "y"')
    hu = interp(np.stack([tr.ravel(), long_.ravel()], axis=-1)).reshape(tr.shape)
    _set_transmission(opt, -(np.sin(theta) + np.sin(theta_r)) * hu * scale)
    return opt


def _set_transmission(opt, opd):
    """Amplitude 1 and the OPD array of shape (ny, nx) into SRWLOptT.arTr (x changes fastest)."""
    flat = np.empty(2 * opd.size)
    flat[0::2] = 1.
    flat[1::2] = opd.ravel()
    if isinstance(opt.arTr, array) and opt.arTr.typecode == 'd' and len(opt.arTr) >= flat.size:
        opt.arTr[:flat.size] = array('d', flat)  # in place (the first photon energy, as the former loops)
    else:
        opt.arTr = array('d', flat)


def Surface_errors(orient, theta, profile, width, length=None, n_long=None, n_tr=None, scale=1., x0=None,
                   theta_r=None, clip=False, after_mirror=True):
    """
    Surface height errors of a mirror (or a grating) as a transmission element, put it right after
    the mirror in a Beamline.

    The sign is that of a real mirror: a height h > 0 is towards the beam (OPD < 0); a profile
    rising downstream (h = s*x) increases the deflection by 2s; a concave profile (h = c*x^2)
    adds the focal power 4c/sin(theta) (checked: WPG_notes/surface/check_sign_frames.py).

    :param orient: plane of deflection, 'x' (horizontal) or 'y' (vertical)
    :param theta: grazing angle of the incident beam at the mirror centre [rad]
    :param profile: (x, h) - 1D profile along the mirror, or (x, y, h) - 2D map with h of shape
        (len(y), len(x)); x along the mirror, increasing downstream, and y across it [m],
        h - height errors [m] (e.g. from :func:`random_profile` or ``np.loadtxt(file).T``)
    :param width: size of the element across the mirror [m] (in the beam cross-section)
    :param length: length of the mirror covered by the element [m], None - the span of x
    :param n_long: number of mesh points along the mirror, None - the number of profile points
    :param n_tr: number of mesh points across the mirror, None - 100 (1D) or len(y) (2D)
    :param scale: factor for the heights
    :param x0: profile point placed at the beam axis [m], None - the centre of the span of x
    :param theta_r: grazing angle of the reflected beam [rad], None - theta (mirror)
    :param clip: False - outside the mesh the transmission is that of its boundary (the mirror
        element of SRW limits the beam), True - zero (the element is the aperture of the mirror)
    :param after_mirror: True - the element is after an SRW mirror (SRWLOptMir*), whose output frame
        is inverted in the plane of deflection (a beam 50 um off axis at the mirror is -50 um after
        it): the downstream end of the mirror is at the negative coordinate. False - the unfolded
        scheme without an SRW mirror (as Mirror_plane): the downstream end at the positive coordinate
    :return: ``SRWLOptT``
    """
    from srwpy.srwlib import SRWLOptT
    theta_r = theta if theta_r is None else theta_r
    if len(profile) == 2:
        x, h = _sorted_profile(*profile)
        y = None
    elif len(profile) == 3:
        x, y, h = (np.asarray(v, dtype=float) for v in profile)
    else:
        raise ValueError('profile should be (x, h) or (x, y, h)')
    x0 = 0.5 * (x[0] + x[-1]) if x0 is None else x0
    x = x - x0
    if after_mirror:
        x = -x[::-1]
        h = h[::-1] if y is None else h[:, ::-1]
    length = x[-1] - x[0] if length is None else length
    n_long = x.size if n_long is None else int(n_long)
    n_tr = (100 if y is None else y.size) if n_tr is None else int(n_tr)
    size_long = length * np.sin(theta_r)
    if orient == 'x':
        opt = SRWLOptT(n_long, n_tr, size_long, width, _extTr=0 if clip else 1)
    elif orient == 'y':
        opt = SRWLOptT(n_tr, n_long, width, size_long, _extTr=0 if clip else 1)
    else:
        raise TypeError('orient should be "x" or "y"')
    if y is None:
        return fill_opd_1d(opt, x, h, orient, theta, theta_r, scale)
    return fill_opd_2d(opt, x, y, h, orient, theta, theta_r, scale)


def _power_law_filter(freq, exponent, f_min):
    """sqrt(PSD) of a power law f^exponent, flat below f_min (roll-off), 0 at f = 0."""
    f = np.maximum(np.abs(freq), f_min)
    amp = f ** (exponent / 2.)
    amp[freq == 0] = 0.
    return amp


def random_profile(length, n, sigma, exponent=-2., f_min=None, seed=None):
    """
    Random 1D height profile with a power-law PSD, ~ f^exponent for f > f_min and flat below.

    :param length: profile length [m]
    :param n: number of points
    :param sigma: RMS height [m]; every realization is normalized to exactly sigma (mean 0)
    :param exponent: PSD exponent (negative; -2 ... -3 are typical for polished X-ray mirrors)
    :param f_min: roll-off spatial frequency [1/m], None - 1/length
    :param seed: seed of the random generator (numpy.random.default_rng)
    :return: (x, h), x from -length/2 to length/2
    """
    rng = np.random.default_rng(seed)
    dx = length / (n - 1)
    f = np.fft.rfftfreq(n, dx)
    f_min = 1. / length if f_min is None else f_min
    spec = _power_law_filter(f, exponent, f_min) * (rng.normal(size=f.size) + 1j * rng.normal(size=f.size))
    h = np.fft.irfft(spec, n)
    h -= h.mean()
    h *= sigma / h.std()
    return np.linspace(-length / 2, length / 2, n), h


def random_surface(length, width, n_long, n_tr, sigma, exponent=-3., f_min=None, seed=None):
    """
    Random isotropic 2D height map with a power-law PSD, ~ |f|^exponent for |f| > f_min and flat below.

    :param length: size along the mirror [m]
    :param width: size across the mirror [m]
    :param n_long: number of points along
    :param n_tr: number of points across
    :param sigma: RMS height [m]; every realization is normalized to exactly sigma (mean 0)
    :param exponent: 2D PSD exponent (negative; for an isotropic surface the 1D PSD of its line
        profiles has the exponent larger by 1 at frequencies well above 1/width: -2.13 instead of -2
        was obtained for exponent -3, 0.8 m x 20 mm, 2001 x 101 points)
    :param f_min: roll-off spatial frequency [1/m], None - 1/length
    :param seed: seed of the random generator
    :return: (x, y, h) with h of shape (n_tr, n_long)
    """
    rng = np.random.default_rng(seed)
    fx = np.fft.rfftfreq(n_long, length / (n_long - 1))
    fy = np.fft.fftfreq(n_tr, width / (n_tr - 1))
    fr = np.hypot(fx[None, :], fy[:, None])
    f_min = 1. / length if f_min is None else f_min
    spec = _power_law_filter(fr, exponent, f_min) * (rng.normal(size=fr.shape) + 1j * rng.normal(size=fr.shape))
    h = np.fft.irfft2(spec, s=(n_tr, n_long))
    h -= h.mean()
    h *= sigma / h.std()
    return np.linspace(-length / 2, length / 2, n_long), np.linspace(-width / 2, width / 2, n_tr), h


def rms_slope(x, h):
    """RMS slope of a 1D profile [rad] (finite differences)."""
    return float(np.std(np.diff(h) / np.diff(x)))
